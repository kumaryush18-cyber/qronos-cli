// /init: the scan must actually read the project, not write a generic template.
import { afterEach, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { renderQronosMd, runInit, scanProject } from "../src/init-cmd";

const made: string[] = [];

function fixture(files: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), "qronos-init-"));
  made.push(dir);
  for (const [path, body] of Object.entries(files)) {
    const full = join(dir, path);
    mkdirSync(join(full, ".."), { recursive: true });
    writeFileSync(full, body);
  }
  return dir;
}

afterEach(() => {
  while (made.length > 0) {
    const dir = made.pop();
    if (dir) rmSync(dir, { recursive: true, force: true });
  }
});

const BUN_TS_PROJECT = {
  "package.json": JSON.stringify({
    name: "demo-app",
    description: "A demo service for tests.",
    type: "module",
    scripts: { build: "tsc", test: "bun test", lint: "eslint .", typecheck: "tsc --noEmit" },
    devDependencies: { typescript: "5.9.3", eslint: "9.0.0" },
  }),
  "bun.lock": "",
  "tsconfig.json": JSON.stringify({ compilerOptions: { strict: true } }),
  ".editorconfig": "root = true\n[*]\nindent_style = space\nindent_size = 2\n",
  "README.md": "# demo-app\n\nA small service that does demo things.\n",
  "src/index.ts": "export const main = () => 1;\n",
  "src/util/math.ts": "export const add = (a: number, b: number) => a + b;\n",
  "test/math.test.ts": "import { test } from 'bun:test';\ntest('add', () => {});\n",
  "node_modules/junk/index.js": "should be ignored\n",
};

describe("scanProject", () => {
  test("detects the real package manager, scripts and stack", () => {
    const scan = scanProject(fixture(BUN_TS_PROJECT));
    expect(scan.packageManager).toBe("bun");
    expect(scan.commands.test).toBe("bun run test");
    expect(scan.commands.typecheck).toBe("bun run typecheck");
    expect(scan.projectName).toBe("demo-app");
    expect(scan.stack).toContain("TypeScript");
    expect(scan.testFramework).toBe("bun test");
  });

  test("finds entry points, test files and ignores node_modules", () => {
    const scan = scanProject(fixture(BUN_TS_PROJECT));
    expect(scan.entryPoints).toContain("src/index.ts");
    expect(scan.testFiles).toBe(1);
    expect(scan.fileCount).toBeGreaterThan(0);
    expect(scan.fileCount).toBeLessThan(20);
  });

  test("reads conventions from tsconfig and .editorconfig", () => {
    const scan = scanProject(fixture(BUN_TS_PROJECT));
    expect(scan.conventions.join(" ")).toContain("strict");
    expect(scan.conventions.join(" ")).toContain("2 spaces");
  });

  test("uses npm when only package.json is present (no lockfile)", () => {
    const scan = scanProject(
      fixture({ "package.json": JSON.stringify({ name: "p", scripts: { test: "jest" } }) }),
    );
    expect(scan.packageManager).toBe("npm");
    expect(scan.commands.test).toBe("npm test");
  });

  test("a python project gets pytest and ruff", () => {
    const scan = scanProject(fixture({ "pyproject.toml": "[project]\nname='x'\n", "main.py": "print(1)\n" }));
    expect(scan.stack).toContain("Python");
    expect(scan.commands.test).toBe("pytest");
    expect(scan.commands.lint).toBe("ruff check .");
  });

  test("an empty folder still scans without throwing", () => {
    const scan = scanProject(fixture({}));
    expect(scan.fileCount).toBe(0);
    expect(scan.commands.test).toBeUndefined();
  });
});

describe("renderQronosMd", () => {
  test("includes every section and the detected commands", () => {
    const md = renderQronosMd(scanProject(fixture(BUN_TS_PROJECT)));
    for (const heading of ["## 1. Overview", "## 2. Commands", "## 3. Project structure", "## 4. Conventions", "## 5. Testing", "## 6. Working agreement"]) {
      expect(md).toContain(heading);
    }
    expect(md).toContain("bun run test");
    expect(md).toContain("src/index.ts");
    expect(md).toContain("Generated by");
  });
});

describe("runInit", () => {
  test("writes QRONOS.md and reports the sections", async () => {
    const cwd = fixture(BUN_TS_PROJECT);
    const notes: string[] = [];
    const ctx = {
      cwd,
      ui: { confirm: async () => true, notify: (m: string) => notes.push(m) },
    };
    await runInit(ctx as any);
    expect(existsSync(join(cwd, "QRONOS.md"))).toBe(true);
    const body = readFileSync(join(cwd, "QRONOS.md"), "utf8");
    expect(body).toContain("demo-app");
    expect(notes.join(" ")).toContain("QRONOS.md created");
  });

  test("declining the overwrite keeps the existing file untouched", async () => {
    const cwd = fixture({ ...BUN_TS_PROJECT, "QRONOS.md": "keep me\n" });
    const ctx = {
      cwd,
      ui: { confirm: async () => false, notify: () => {} },
    };
    await runInit(ctx as any);
    expect(readFileSync(join(cwd, "QRONOS.md"), "utf8")).toBe("keep me\n");
  });
});
