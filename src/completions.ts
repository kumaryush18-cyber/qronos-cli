// Shell completion scripts for qronos-cli, generated from one small spec.
//
// Why generate instead of shipping three hand-written scripts: the flag list
// changes (--session came later, --dangerously-skip-permissions later still),
// and three files drift apart immediately. Here a new flag is one array entry,
// and completions.test.ts runs `bash -n` on the output so a broken script fails
// the test suite, not the user's shell.
//
// Install:
//   qronos-cli completions bash >> ~/.bash_completion
//   qronos-cli completions zsh  >  "${fpath[1]}/_qronos-cli"
//   qronos-cli completions fish >  ~/.config/fish/completions/qronos-cli.fish

export const COMPLETION_SHELLS = ["bash", "zsh", "fish"] as const;
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

export interface FlagSpec {
  long: string;
  short?: string;
  /** Shown by zsh/fish and used for --help parity. */
  description: string;
  /** Fixed values, if this flag takes one. */
  values?: string[];
}

export interface CompletionSpec {
  command: string;
  subcommands: { name: string; description: string }[];
  flags: FlagSpec[];
  providers: string[];
  mcpCommands: string[];
  shells: readonly CompletionShell[];
}

export const COMPLETION_SPEC: CompletionSpec = {
  command: "qronos-cli",
  subcommands: [
    { name: "init", description: "create QRONOS.md project instructions" },
    { name: "mcp", description: "manage MCP tools" },
    { name: "completions", description: "print a shell completion script" },
    { name: "logout", description: "sign out of Qronos" },
    { name: "help", description: "show help" },
    { name: "version", description: "print the CLI version" },
  ],
  flags: [
    { long: "--continue", short: "-c", description: "continue the most recent session" },
    { long: "--resume", short: "-r", description: "resume the most recent session" },
    { long: "--session", short: "-s", description: "resume a session by id" },
    { long: "--provider", short: "-p", description: "use a specific provider", values: [] },
    { long: "--api-key", short: "-k", description: "supply a direct API key" },
    { long: "--base-url", short: "-u", description: "custom OpenAI-compatible endpoint" },
    { long: "--model", short: "-m", description: "use a specific model" },
    { long: "--dangerously-skip-permissions", description: "skip permission prompts" },
    { long: "--help", short: "-h", description: "show help" },
    { long: "--version", short: "-v", description: "print the CLI version" },
  ],
  providers: ["qronos", "openai", "anthropic", "deepseek", "ollama"],
  mcpCommands: ["add", "remove", "list", "login", "logout"],
  shells: COMPLETION_SHELLS,
};

export function isCompletionShell(value: string): value is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(value);
}

function allFlagWords(spec: CompletionSpec): string[] {
  return spec.flags.flatMap((flag) => [flag.long, ...(flag.short ? [flag.short] : [])]);
}

const quote = (value: string) => `'${value.replace(/'/g, `'\\''`)}'`;

/** Bash: a function bound with `complete -F`. */
function bashScript(spec: CompletionSpec): string {
  const subcommands = spec.subcommands.map((s) => s.name).join(" ");
  const flags = allFlagWords(spec).join(" ");
  const providers = spec.providers.join(" ");
  const mcp = spec.mcpCommands.join(" ");
  return `# ${spec.command} completion for bash. Generated by \`${spec.command} completions bash\`.
_${spec.command.replace(/-/g, "_")}() {
    local cur prev
    COMPREPLY=()
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"

    case "\${prev}" in
        --provider|-p)
            COMPREPLY=( $(compgen -W ${quote(providers)} -- "\${cur}") )
            return 0
            ;;
        completions)
            COMPREPLY=( $(compgen -W ${quote(spec.shells.join(" "))} -- "\${cur}") )
            return 0
            ;;
        mcp)
            COMPREPLY=( $(compgen -W ${quote(mcp)} -- "\${cur}") )
            return 0
            ;;
    esac

    if [ "\${COMP_CWORD}" -eq 1 ]; then
        COMPREPLY=( $(compgen -W ${quote(`${subcommands} ${flags}`)} -- "\${cur}") )
    else
        COMPREPLY=( $(compgen -W ${quote(flags)} -- "\${cur}") )
    fi
    return 0
}
complete -F _${spec.command.replace(/-/g, "_")} ${spec.command}
`;
}

/** Zsh: `#compdef` file, using `_arguments` so descriptions show. */
function zshScript(spec: CompletionSpec): string {
  const pairs = spec.flags
    .map((flag) => {
      const names = [flag.long, ...(flag.short ? [flag.short] : [])].join(" ");
      const action = flag.values && flag.values.length ? `:value:(${flag.values.join(" ")})` : flag.long === "--provider" ? ":provider:(" + spec.providers.join(" ") + ")" : "";
      return `        ${JSON.stringify(names).replace(/"/g, "")}${action ? `[${flag.description}]${action}` : `[${flag.description}]`}`;
    })
    .join("\n");
  const commands = spec.subcommands.map((s) => `        ${JSON.stringify(s.name).replace(/"/g, "")}:${s.description}`).join("\n");
  return `#compdef ${spec.command}
# ${spec.command} completion for zsh. Generated by \`${spec.command} completions zsh\`.
_${spec.command.replace(/-/g, "_")}() {
    local -a commands
    commands=(
${commands}
    )
    _arguments -s -S \\
${pairs} \\
        '1:command:->command' \\
        '*::arg:->args'
    case $state in
        command)
            _describe -t commands '${spec.command} command' commands
            ;;
        args)
            case $words[1] in
                mcp) _values 'mcp command' ${spec.mcpCommands.join(" ")} ;;
                completions) _values 'shell' ${spec.shells.join(" ")} ;;
            esac
            ;;
    esac
}
compdef _${spec.command.replace(/-/g, "_")} ${spec.command}
`;
}

/** Fish: one `complete` line per flag, which is fish's native style. */
function fishScript(spec: CompletionSpec): string {
  const name = spec.command;
  const lines = [`# ${name} completion for fish. Generated by \`${name} completions fish\`.`];
  for (const sub of spec.subcommands) {
    lines.push(`complete -c ${name} -n "__fish_use_subcommand" -a ${quote(sub.name)} -d ${quote(sub.description)}`);
  }
  for (const flag of spec.flags) {
    const short = flag.short ? ` -s ${flag.short.replace(/^-/, "")}` : "";
    lines.push(`complete -c ${name} -l ${flag.long.replace(/^--/, "")}${short} -d ${quote(flag.description)}`);
  }
  lines.push(`complete -c ${name} -n "__fish_seen_subcommand_from mcp" -a ${quote(spec.mcpCommands.join(" "))}`);
  lines.push(`complete -c ${name} -n "__fish_seen_subcommand_from completions" -a ${quote(spec.shells.join(" "))}`);
  lines.push(`complete -c ${name} -l provider -a ${quote(spec.providers.join(" "))}`);
  return `${lines.join("\n")}\n`;
}

export function completionScript(shell: CompletionShell, spec: CompletionSpec = COMPLETION_SPEC): string {
  if (shell === "bash") return bashScript(spec);
  if (shell === "zsh") return zshScript(spec);
  return fishScript(spec);
}

/** One-line install hint printed after the script on stderr. */
export function completionInstallHint(shell: CompletionShell, command = COMPLETION_SPEC.command): string {
  if (shell === "bash") return `Add this to ~/.bash_completion, then restart the shell: ${command} completions bash > ~/.bash_completion.d/${command}`;
  if (shell === "zsh") return `Save it as a file named _${command} inside a directory on $fpath: ${command} completions zsh > "\${fpath[1]}/_${command}"`;
  return `Save it as ~/.config/fish/completions/${command}.fish: ${command} completions fish > ~/.config/fish/completions/${command}.fish`;
}
